function redirect(request, path, params) {
  const next = new URL(request.url); next.pathname = path;
  if(params) for(const [key,value] of Object.entries(params)) next.searchParams.set(key,value);
  return new Response(null,{status:302,headers:{Location:next.href,'Cache-Control':'no-store'}});
}
async function page(context, asset) {
  let response = await context.env.ASSETS.fetch(new URL(asset,context.request.url));
  // Pages may normalise .html to an extensionless file. Follow that internally.
  for(let hop=0;hop<3 && response.status>=300 && response.status<400 && response.headers.get('Location');hop++){
    const next=new URL(response.headers.get('Location'),context.request.url);
    if(next.origin!==new URL(context.request.url).origin || !next.pathname.startsWith(asset.replace(/\.html$/, ''))) return new Response('Page unavailable',{status:502});
    response=await context.env.ASSETS.fetch(next);
  }
  if(response.status>=300 && response.status<400) return new Response('Page unavailable',{status:502});
  const result = new Response(response.body,response);
  result.headers.set('Cache-Control','no-store');
  result.headers.set('Referrer-Policy','no-referrer');
  return result;
}
